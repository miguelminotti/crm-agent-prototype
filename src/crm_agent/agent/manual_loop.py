from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import AIMessage, BaseMessage, ToolMessage
from langchain_core.tools import BaseTool


class MaxIterationsReached(Exception):
    """
    Exception raised when the maximum number of iterations is reached
    in the agent loop.
    """

    pass


def run_agent(
    model: BaseChatModel,
    tools: list[BaseTool],
    messages: list[BaseMessage],
    *,
    max_iterations: int = 10,
    current_iteration: int = 0,
) -> list[BaseMessage]:
    """
    Run an agent with the specified model, tools, and messages.

    Args:
        model (BaseChatModel): The model to use for the agent.
        tools (list[BaseTool]): A list of tools available to the agent.
        messages (list[BaseMessage]): A list of messages to process.
        max_iterations (int, optional): The maximum number of iterations to run the
        agent. Defaults to 10.
        current_iteration (int, optional): The current iteration count. Defaults to 0.

    Returns:
        list[BaseMessage]: The list of messages generated by the agent.
    """
    # Copy the current messages to avoid modifying the original list
    history = messages.copy()

    # Call the model
    answer = model.invoke(history)  # Get the last message from the model's response
    history.append(answer)  # Append the model's response to the message list

    # Execute any tool calls in the answer (if applicable)
    if isinstance(answer, AIMessage):
        for tool_call in answer.tool_calls:
            tool = _tools_by_name(tools).get(tool_call["name"])
            if tool:
                tool_use_message: ToolMessage = tool.invoke(tool_call)
                history.append(tool_use_message)
            else:
                message = (
                    f"Tool '{tool_call['name']}' not found. "
                    f"Available tools: {[t.name for t in tools]}"
                )
                history.append(ToolMessage(content=message))

    # Check if there's still tool calls remaining
    if (
        any(tool_call for tool_call in answer.tool_calls)
        and current_iteration < max_iterations
    ):
        return run_agent(
            model,
            tools,
            history,
            max_iterations=max_iterations,
            current_iteration=current_iteration + 1,
        )

    # If no tool calls remain or max iterations reached, return the messages as is
    if current_iteration >= max_iterations:
        raise MaxIterationsReached(f"Maximum iterations of {max_iterations} reached.")
    return history


def _tools_by_name(tools: list[BaseTool]) -> dict[str, BaseTool]:
    return {tool.name: tool for tool in tools}
