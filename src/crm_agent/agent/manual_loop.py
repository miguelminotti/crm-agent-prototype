from collections.abc import Sequence

from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import AIMessage, BaseMessage, ToolMessage
from langchain_core.tools import BaseTool
from pydantic import ValidationError


class MaxIterationsReachedError(Exception):
    """
    Exception raised when the maximum number of iterations is reached
    in the agent loop.
    """


def run_agent(
    model: BaseChatModel,
    tools: Sequence[BaseTool],
    messages: Sequence[BaseMessage],
    *,
    max_iterations: int = 10,
) -> list[BaseMessage]:
    """
    Run an agent with the specified model, tools, and messages.

    Args:
        model (BaseChatModel): The model to use for the agent.
        tools (Sequence[BaseTool]): A sequence of tools available to the agent.
        messages (Sequence[BaseMessage]): A sequence of messages to process.
        max_iterations (int, optional): The maximum number of iterations to run the
        agent. Defaults to 10.

    Returns:
        list[BaseMessage]: The list of messages generated by the agent.
    """
    history = list(messages)
    tools_dict = _tools_by_name(tools)

    for _ in range(max_iterations):
        answer: AIMessage = model.invoke(history)
        history.append(answer)

        for tool_call in answer.tool_calls:
            tool = tools_dict.get(tool_call["name"])
            if tool is not None:
                if isinstance(tool_call["id"], str):
                    raise ValueError("Tool call ID cannot be None.")

                try:
                    tool_use_message: ToolMessage = tool.invoke(tool_call)
                except ValidationError as e:
                    error_tool_message = ToolMessage(
                        tool_call_id=tool_call["id"],
                        content=f"Validation error: "
                        f"{e.errors(include_url=False)[0]['msg']}",
                        status="error",
                    )
                    history.append(error_tool_message)
                else:
                    history.append(tool_use_message)
            else:
                error_tool_message = ToolMessage(
                    tool_call_id=tool_call["id"],
                    content=f"Tool '{tool_call['name']}' not found. "
                    f"Available tools: {list(tools_dict)}",
                    status="error",
                )
                history.append(error_tool_message)

        if not answer.tool_calls:
            return history

    raise MaxIterationsReachedError(f"Maximum iterations of {max_iterations} reached.")


def _tools_by_name(tools: Sequence[BaseTool]) -> dict[str, BaseTool]:
    return {tool.name: tool for tool in tools}
